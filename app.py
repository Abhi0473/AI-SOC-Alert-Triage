"""
Phase 5: Streamlit Dashboard
------------------------------
Alert list (left) + full evidence-trail detail view (right): Detection ->
Enrichment -> Risk Score -> AI Analysis -> Analyst Verdict. This is the
"click an alert, walk through the reasoning" surface for a live interview demo.

Run with:  streamlit run app.py
"""

import json
import os

import streamlit as st

from src.pipeline import run_pipeline

st.set_page_config(page_title="SOC AI-Assisted Triage", layout="wide")

DATA_PATH = os.path.join(os.path.dirname(__file__), "data", "alerts_output.json")
VERDICTS_PATH = os.path.join(os.path.dirname(__file__), "data", "analyst_verdicts.json")


def load_verdicts() -> dict:
    """Analyst verdicts persist across app restarts in a small JSON file --
    intentionally simple (no DB) for a portfolio project, but real: a
    verdict you set survives closing and reopening the dashboard."""
    if os.path.exists(VERDICTS_PATH):
        try:
            with open(VERDICTS_PATH) as f:
                return json.load(f)
        except (json.JSONDecodeError, OSError):
            return {}
    return {}


def save_verdict(alert_id: str, verdict: str) -> None:
    verdicts = load_verdicts()
    verdicts[alert_id] = verdict
    with open(VERDICTS_PATH, "w") as f:
        json.dump(verdicts, f, indent=2)

SEVERITY_COLOR = {
    "critical": "🟥",
    "high": "🟧",
    "medium": "🟨",
    "low": "🟩",
}
VERDICT_EMOJI = {
    "escalate": "🚨",
    "monitor": "👁️",
    "close_as_benign": "✅",
}


@st.cache_data(show_spinner="Running pipeline...")
def load_alerts(_refresh_token: int):
    return run_pipeline()


def main():
    st.title("🛡️ AI-Assisted SOC Alert Investigation & Triage Platform")
    st.caption(
        "Alerts flow through detection → enrichment → deterministic risk scoring → "
        "AI analyst assistance. The AI never makes the final call — a human analyst does."
    )

    if "refresh_token" not in st.session_state:
        st.session_state.refresh_token = 0

    with st.sidebar:
        st.header("Pipeline")
        if not os.environ.get("ANTHROPIC_API_KEY"):
            st.info("No ANTHROPIC_API_KEY set — AI layer is running in **mock mode** "
                     "(deterministic, templated reasoning, zero cost). Set the env var "
                     "to use live Claude analysis.")
        else:
            st.success("ANTHROPIC_API_KEY detected — AI layer will call Claude live.")
        if st.button("🔄 Re-run pipeline"):
            st.session_state.refresh_token += 1
            st.cache_data.clear()

        st.divider()
        st.header("Architecture")
        st.code(
            "Telemetry -> Detection -> Normalize\n"
            "  -> Enrichment (IOC + MITRE)\n"
            "  -> Deterministic Risk Score\n"
            "  -> AI Analyst Assistance\n"
            "  -> Analyst Verdict",
            language=None,
        )

    alerts = load_alerts(st.session_state.refresh_token)

    if not alerts:
        st.warning("No alerts generated by the current dataset.")
        return

    persisted_verdicts = load_verdicts()
    for a in alerts:
        if a["alert_id"] in persisted_verdicts:
            a["analyst_verdict"] = persisted_verdicts[a["alert_id"]]

    left, right = st.columns([1, 2], gap="large")

    with left:
        st.subheader(f"Alert Queue ({len(alerts)})")
        labels = []
        for a in alerts:
            sev = a["risk"]["severity"]
            labels.append(f"{SEVERITY_COLOR.get(sev, '')} {a['alert_id']}  ·  {sev.upper()}  ·  {a['host']}")

        selected_idx = st.radio(
            "Select an alert to investigate:",
            options=list(range(len(alerts))),
            format_func=lambda i: labels[i],
            label_visibility="collapsed",
        )

    alert = alerts[selected_idx]

    with right:
        render_alert_detail(alert)


def render_alert_detail(alert: dict):
    sev = alert["risk"]["severity"]
    st.subheader(f"{SEVERITY_COLOR.get(sev,'')} {alert['alert_id']}  —  {sev.upper()} SEVERITY")

    c1, c2, c3 = st.columns(3)
    c1.metric("Host", alert["host"])
    c2.metric("User", alert["user"])
    c3.metric("Risk Score", alert["risk"]["score"])

    st.markdown("#### 1 · Detection")
    for rule in alert["fired_rules"]:
        st.markdown(f"- **{rule['rule_name']}** (`{rule['rule_id']}`) — {rule['description']}")
    st.code(f"Process: {alert['process']}\nParent process: {alert['parent_process']}\n"
            f"Command line: {alert['command_line']}\nDestination IP: {alert['destination_ip']}", language=None)

    st.markdown("#### 2 · Enrichment")
    ip_intel = alert["enrichment"]["ip_reputation"]
    mitre = alert["enrichment"]["mitre"]
    ec1, ec2 = st.columns(2)
    with ec1:
        st.markdown("**Threat Intel (IOC)**")
        if ip_intel:
            st.json(ip_intel, expanded=False)
        else:
            st.write("No destination IP to enrich.")
    with ec2:
        st.markdown("**MITRE ATT&CK Mapping**")
        if mitre:
            for m in mitre:
                st.write(f"`{m['technique_id']}` — {m['technique_name']} ({m['tactic']})")
        else:
            st.write("No technique mapped.")

    st.markdown("#### 3 · Deterministic Risk Score")
    st.write(f"**Total: {alert['risk']['score']} → {alert['risk']['severity'].upper()}**")
    st.table({"signal": list(alert["risk"]["breakdown"].keys()),
              "points": list(alert["risk"]["breakdown"].values())})

    st.markdown("#### 4 · AI Analyst Assistance")
    ai = alert["ai_analysis"]
    mode_note = ai.get("_mode", "unknown")
    st.caption(f"AI mode: `{mode_note}`")
    v1, v2 = st.columns(2)
    v1.markdown(f"**Verdict:** {VERDICT_EMOJI.get(ai['verdict'], '')} `{ai['verdict']}`")
    v2.markdown(f"**Confidence:** `{ai['confidence']}`")
    st.markdown("**Evidence:**")
    for e in ai["evidence"]:
        st.markdown(f"- {e}")
    st.markdown("**Recommended next steps:**")
    for a in ai["recommended_actions"]:
        st.markdown(f"- {a}")

    st.markdown("#### 5 · Analyst Verdict (human-in-the-loop)")
    options = ["pending_review", "confirmed_incident", "false_positive", "monitoring"]
    current = alert.get("analyst_verdict", "pending_review")
    idx = options.index(current) if current in options else 0
    choice = st.selectbox("Set the final verdict for this alert:", options, index=idx, key=f"verdict_{alert['alert_id']}")
    if choice != current:
        save_verdict(alert["alert_id"], choice)
        st.success(f"Saved — {alert['alert_id']} marked as `{choice}`. "
                   "This persists in data/analyst_verdicts.json across restarts. "
                   "The AI's recommendation above was input to this decision, not a replacement for it.")

    if alert.get("ground_truth_verdict"):
        with st.expander("Ground truth (evaluation only — not shown to the AI)"):
            st.write(f"Ground truth: **{alert['ground_truth_verdict']}**")
            st.write(alert.get("ground_truth_notes", ""))


if __name__ == "__main__":
    main()
